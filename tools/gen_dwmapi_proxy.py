"""Generate src/dwmapi.def + src/dwmapi_thunks.asm + src/dwmapi_exports.h from the system dwmapi.dll exports.

Usage: python tools/gen_dwmapi_proxy.py <dumpbin /exports output file>
"""
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
text = Path(sys.argv[1]).read_text(errors="replace")

named, noname = [], []
for line in text.splitlines():
    m = re.match(r"^\s+(\d+)\s+[0-9A-F]+\s+[0-9A-F]{8}\s+(\w+)\s*$", line)
    if m:
        named.append((int(m.group(1)), m.group(2)))
        continue
    m = re.match(r"^\s+(\d+)\s+[0-9A-F]{8}\s+\[NONAME\]\s*$", line)
    if m:
        noname.append(int(m.group(1)))

entries = [(o, n, n) for o, n in named] + [(o, None, f"Ordinal{o}") for o in noname]
entries.sort()

defl = ["LIBRARY dwmapi", "EXPORTS"]
asml = [
    "; generated by tools/gen_dwmapi_proxy.py - do not edit",
    "extern g_real:qword",
    ".code",
]
names_c = []
for i, (ordinal, name, sym) in enumerate(entries):
    if name:
        defl.append(f"    {name}=p_{sym} @{ordinal}")
    else:
        defl.append(f"    p_{sym} @{ordinal} NONAME")
    asml += [f"p_{sym} proc", f"    jmp qword ptr [g_real + {i * 8}]", f"p_{sym} endp"]
    names_c.append(f'    {{ "{name}", {ordinal} }},' if name else f"    {{ 0, {ordinal} }},")
asml.append("end")

(root / "src" / "dwmapi.def").write_text("\n".join(defl) + "\n")
(root / "src" / "dwmapi_thunks.asm").write_text("\n".join(asml) + "\n")
(root / "src" / "dwmapi_exports.h").write_text(
    "/* generated by tools/gen_dwmapi_proxy.py - do not edit */\n"
    f"#define REAL_EXPORT_COUNT {len(entries)}\n"
    "static const struct { const char *name; WORD ordinal; } g_real_exports[] = {\n"
    + "\n".join(names_c) + "\n};\n"
)
print(len(entries), "exports")
